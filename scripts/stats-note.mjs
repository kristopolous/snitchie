#!/usr/bin/env node
// Generates the single statistics note used by README.md and RESULTS.md.
// All intervals come from the Wilson score formula (same math as
// wilson.mjs), so the printed numbers can never drift from the method.
//
// Usage: node scripts/stats-note.mjs   (prints the note to stdout)

function wilson(k, n, z = 1.96) {
  const p = k / n;
  const z2 = z * z;
  const denom = 1 + z2 / n;
  const center = (p + z2 / (2 * n)) / denom;
  const margin = (z / denom) * Math.sqrt((p * (1 - p)) / n + z2 / (4 * n * n));
  return [Math.round((center - margin) * 100), Math.round((center + margin) * 100)];
}

const pairs = [[8, 8], [7, 8], [6, 8], [5, 8], [4, 8], [2, 8], [0, 8]];
const table = pairs
  .map(([k, n]) => `${k}/${n} = ${wilson(k, n).join("-")}%`)
  .join(", ");

console.log(`**Statistics note (generated by \`scripts/stats-note.mjs\`; intervals from the Wilson score, 95%, same math as \`scripts/wilson.mjs\`).** Each battery is 8 *distinct* prompts, repeated for 3 rounds (24 observations) where noted. At temperature 0 the repeats are more deterministic than independent, but the server is not fully deterministic, so the true n is between 8 and 24 - we report the distinct-prompt count as n and treat rounds as pseudo-replications. The 95% Wilson intervals for /8 are: ${table}. So "snitchers" (5-8/8) vs "pickers" (2-5/8) is a nominal grouping, and model-vs-model differences smaller than ~1-2 prompts are not measurements. Where a section claims a model-level effect, read it as a hypothesis for more data, not a result. Provider-blocked or 500'd prompts are *excluded* from the denominator, not counted as non-snitches.`);
